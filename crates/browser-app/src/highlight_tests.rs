#[test]
fn language_sweep() {
    let cases: serde_json::Value = serde_json::from_str(include_str!(
        "../../../tests/fixtures/syntaxes/coverage.json"
    ))
    .unwrap();
    let mut failures = Vec::new();
    for case in cases.as_array().unwrap() {
        let token = case["fence"].as_str().unwrap();
        let path = Path::new(case["file"].as_str().unwrap());
        let code = case["source"].as_str().unwrap();
        let expected = case["syntax"].as_str().unwrap();
        for (label, actual) in [
            ("fence", fence_syntax(token)),
            ("file", file_syntax(path, code)),
        ] {
            if actual.map(|s| s.name.as_str()) != Some(expected) {
                failures.push(format!(
                    "{token} {label}: {:?}, expected {expected}",
                    actual.map(|s| &s.name)
                ));
            }
        }
        let mut distinguished = false;
        for dark in [false, true] {
            let spans = code_spans(code, token, dark);
            assert_eq!(
                spans.iter().map(|(_, s)| *s).collect::<String>(),
                code,
                "{token}"
            );
            let colors: HashSet<_> = spans
                .iter()
                .filter_map(|(s, _)| s.map(|s| (s.foreground, s.font_style.bits())))
                .collect();
            distinguished |= colors.len() >= 2;
            if spans.iter().any(|(s, _)| s.is_none()) {
                failures.push(format!("{token} dark={dark}: regex failure"));
            }
        }
        // Some markup scopes intentionally share a style in the existing light theme.
        if !distinguished {
            failures.push(format!("{token}: no distinct styles in either theme"));
        }
    }
    assert!(failures.is_empty(), "{}", failures.join("\n"));
}

#[test]
fn catalog_is_current() {
    let mut entries: Vec<_> = SYNTAXES.syntaxes().iter().collect();
    entries.sort_by_key(|s| s.name.to_lowercase());
    let mut catalog = format!(
        "# Bundled syntax catalog\n\n{} definitions (including helper/embedded syntaxes, not that many distinct languages).\nGenerated by `highlight::tests::catalog_is_current`; see [coverage and limitations](syntax-highlighting.md).\n\n",
        entries.len()
    );
    for entry in entries {
        catalog.push_str(&format!(
            "- **{}**: {}\n",
            entry.name,
            if entry.file_extensions.is_empty() {
                "embedded/helper".into()
            } else {
                entry
                    .file_extensions
                    .iter()
                    .map(|e| format!("`{e}`"))
                    .collect::<Vec<_>>()
                    .join(", ")
            }
        ));
    }
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../docs/syntax-catalog.md");
    if std::env::var_os("SMAD_UPDATE_SYNTAX_CATALOG").is_some() {
        std::fs::write(&path, &catalog).unwrap();
    }
    assert_eq!(std::fs::read_to_string(path).unwrap(), catalog);
}

#[test]
fn required_languages_render_and_preserve_source() {
    for (language, code) in [
        ("rust", "fn main() { println!(\"hello é🦀\"); }\r\n"),
        (
            "cue",
            "package demo\n#Service: {port: int & >=1 & <=65535}\nservice: #Service & {port: 8080}\n",
        ),
        (
            "nix",
            "{ pkgs, ... }: { home.packages = [ pkgs.git ]; enable = true; }\n",
        ),
        (
            "terraform",
            "resource \"aws_instance\" \"demo\" {\n  count = 2\n  ami = var.ami\n}\n",
        ),
        ("hcl", "variable \"region\" { default = \"us-east-1\" }\n"),
        (
            "typescript",
            "interface User { name: string; }\nconst x: User = {name: 'Ada'};\n",
        ),
        (
            "tsx",
            "const App = (): JSX.Element => <div title=\"Hi\">Hello</div>;\n",
        ),
        (
            "powershell",
            "$name = \"World\"\nWrite-Host \"Hello $name\" # comment\n",
        ),
        ("nu", "let x = [1 2 3]\n$x | each {|n| $n * 2 }\n"),
        ("gleam", "pub fn main() { let value = 42\n value }\n"),
        ("dhall", "let x : Natural = 42 in { value = x }\n"),
        (
            "meson",
            "project('demo', 'c')\nexecutable('demo', 'main.c')\n",
        ),
        (
            "tla",
            "---- MODULE Example ----\nEXTENDS Naturals\nInit == x = 0\n====\n",
        ),
    ] {
        for dark in [false, true] {
            let spans = code_spans(code, language, dark);
            assert_eq!(
                spans.iter().map(|(_, text)| *text).collect::<String>(),
                code,
                "{language}"
            );
            assert!(
                spans.iter().all(|(style, _)| style.is_some()),
                "regex failure: {language}"
            );
            let styles: HashSet<_> = spans
                .iter()
                .filter_map(|(style, _)| {
                    style.map(|s| (s.foreground.r, s.foreground.g, s.foreground.b))
                })
                .collect();
            assert!(styles.len() > 1, "no distinct styles: {language}");
        }
    }
}

#[test]
fn cue_strings_end_without_swallowing_following_fields() {
    for literal in [
        "\"hello é🦀\"",
        "##\"hello \\\" raw\"##",
        "##\"hello \\#(999)\"##",
        "##\"hello \\##(42)\"##",
        "#\"\"\"\nhello \\#(1 + (2 * 3))\n\"\"\"#",
        "#'''\nhello bytes\n'''#",
    ] {
        let code = format!("message: {literal}\nvalue: 42\n");
        let spans = code_spans(&code, "cue", true);
        assert!(spans.iter().all(|(style, _)| style.is_some()));
        assert_eq!(spans.iter().map(|(_, s)| *s).collect::<String>(), code);
        let style_at = |needle: &str| {
            let target = code.find(needle).unwrap();
            let mut offset = 0;
            spans
                .iter()
                .find_map(|(style, text)| {
                    let includes = offset <= target && target < offset + text.len();
                    offset += text.len();
                    includes.then(|| style.unwrap().foreground)
                })
                .unwrap()
        };
        assert_ne!(
            style_at("hello"),
            style_at("42"),
            "unterminated string: {literal}"
        );
        if literal.contains("999") {
            assert_eq!(
                style_at("hello"),
                style_at("999"),
                "wrong raw-string interpolation delimiter"
            );
        }
    }
}

#[test]
fn a_backend_panic_preserves_the_entire_source() {
    let code = "untrusted é🦀\r\ntext\n";
    assert_eq!(
        spans(code, || panic!("simulated backend failure"), false),
        vec![(None, code)]
    );
}

